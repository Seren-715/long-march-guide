import {readFile,writeFile} from 'node:fs/promises';
import {nodes} from '../src/data.js';
const html=await readFile(new URL('../src/page.html',import.meta.url),'utf8');
const server=await readFile(new URL('../src/server.js',import.meta.url),'utf8');
const data=JSON.stringify({nodes}).replaceAll('<','\\u003c');
const page=html.replace('__DATA__',()=>data);
if(page===html) throw new Error('Missing data marker');
const output=server.replace("import { nodes } from './data.js';",()=> 'const nodes = '+JSON.stringify(nodes)+';').replace('PAGE',()=>JSON.stringify(page));
await writeFile(new URL('../worker/index.js',import.meta.url),output);
console.log('Worker generated');
